
    create table audit_logs (
        actor_id bigint,
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        target_id bigint,
        target_type varchar(20) not null,
        action varchar(40) not null,
        actor_email varchar(150),
        details varchar(500),
        primary key (id)
    );

    create table cart_items (
        price_when_added numeric(10,2),
        quantity integer not null,
        id bigint generated by default as identity,
        product_id bigint not null,
        user_id bigint not null,
        primary key (id),
        unique (user_id, product_id)
    );

    create table categories (
        id bigint generated by default as identity,
        icon varchar(10),
        name varchar(100) not null unique,
        primary key (id)
    );

    create table checkouts (
        total_amount numeric(10,2) not null,
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        user_id bigint not null,
        payment_method varchar(10) not null check (payment_method in ('COD','UPI')),
        request_id varchar(64) not null,
        primary key (id),
        constraint uk_checkout_user_request unique (user_id, request_id)
    );

    create table coupons (
        active boolean not null,
        discount_value numeric(10,2) not null,
        max_discount numeric(10,2),
        min_order numeric(10,2) not null,
        per_user_limit integer not null,
        expires_at timestamp(6),
        id bigint generated by default as identity,
        coupon_type varchar(10) not null check (coupon_type in ('PERCENT','FLAT')),
        code varchar(30) not null unique,
        description varchar(150) not null,
        primary key (id)
    );

    create table notifications (
        is_read boolean,
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        user_id bigint not null,
        title varchar(120) not null,
        link varchar(200),
        body varchar(300),
        primary key (id)
    );

    create table order_issues (
        quantity integer not null,
        refund_amount numeric(10,2) not null,
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        order_id bigint not null,
        order_item_id bigint not null,
        reason varchar(20) not null check (reason in ('MISSING','DAMAGED','EXPIRED')),
        status varchar(30) not null,
        product_name varchar(150) not null,
        note varchar(300),
        primary key (id)
    );

    create table order_items (
        gst_percent integer,
        price numeric(10,2) not null,
        quantity integer not null,
        id bigint generated by default as identity,
        order_id bigint not null,
        product_id bigint,
        product_name varchar(150) not null,
        primary key (id)
    );

    create table orders (
        delivery_fee numeric(10,2) not null,
        discount numeric(10,2) not null,
        gst_included numeric(10,2) not null,
        slot_date date,
        slot_end time(6),
        slot_start time(6),
        stock_released boolean,
        subtotal numeric(10,2) not null,
        total_amount numeric(10,2) not null,
        pincode varchar(6),
        checkout_id bigint,
        created_at timestamp(6) not null,
        delivered_at timestamp(6),
        id bigint generated by default as identity,
        shop_id bigint,
        updated_at timestamp(6),
        user_id bigint not null,
        version bigint,
        fulfilment varchar(10) check (fulfilment in ('DELIVERY','PICKUP')),
        payment_method varchar(10) not null check (payment_method in ('COD','UPI')),
        payment_status varchar(20) not null check (payment_status in ('PENDING','COD_PENDING','PAID','FAILED','REFUNDED','NOT_CHARGED')),
        substitution_preference varchar(20) check (substitution_preference in ('REPLACE_SIMILAR','REFUND_ITEM','CALL_ME')),
        coupon_code varchar(30),
        status varchar(30) not null check (status in ('PAYMENT_PENDING','PLACED','ACCEPTED','PREPARING','PACKED','READY_FOR_PICKUP','OUT_FOR_DELIVERY','DELIVERED','CANCELLED','PAYMENT_FAILED')),
        request_id varchar(64),
        status_note varchar(250),
        rejection_reason varchar(300),
        shipping_address varchar(300),
        primary key (id),
        constraint uk_order_user_request unique (user_id, request_id)
    );

    create table products (
        active boolean,
        expiry_date date,
        gst_percent integer,
        mrp numeric(10,2),
        price numeric(10,2) not null,
        rating_count integer,
        rating_total integer,
        stock integer not null,
        category_id bigint,
        id bigint generated by default as identity,
        shop_id bigint,
        image_emoji varchar(10),
        unit varchar(20),
        brand varchar(60),
        name varchar(150) not null,
        description varchar(500),
        image_url varchar(500),
        primary key (id),
        check (stock >= 0)
    );

    create table reports (
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        product_id bigint,
        reporter_id bigint not null,
        resolved_at timestamp(6),
        shop_id bigint not null,
        status varchar(12) not null check (status in ('OPEN','RESOLVED','DISMISSED')),
        reason varchar(30) not null check (reason in ('WRONG_PRICE','EXPIRED_OR_BAD_QUALITY','MISLEADING_INFO','FAKE_SHOP','RUDE_OR_UNSAFE','OTHER')),
        resolved_by varchar(150),
        resolution_note varchar(300),
        details varchar(500),
        primary key (id)
    );

    create table reviews (
        hidden boolean,
        rating integer not null,
        buyer_id bigint not null,
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        product_id bigint not null,
        shop_id bigint not null,
        updated_at timestamp(6),
        hidden_reason varchar(300),
        comment varchar(500),
        primary key (id),
        constraint uk_review_buyer_product unique (product_id, buyer_id)
    );

    create table saved_items (
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        product_id bigint not null,
        user_id bigint not null,
        primary key (id),
        constraint uk_saved_user_product unique (user_id, product_id)
    );

    create table shops (
        accepting_orders boolean not null,
        close_time time(6) not null,
        delivery_fee numeric(10,2) not null,
        free_delivery_above numeric(10,2),
        latitude float(53),
        longitude float(53),
        min_order_amount numeric(10,2) not null,
        offers_delivery boolean not null,
        offers_pickup boolean not null,
        open_time time(6) not null,
        rating_count integer,
        rating_total integer,
        slot_capacity integer,
        slots_enabled boolean,
        pincode varchar(6) not null,
        approved_at timestamp(6),
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        owner_id bigint not null,
        version bigint,
        status varchar(12) not null check (status in ('PENDING','APPROVED','REJECTED','SUSPENDED')),
        gstin varchar(15),
        phone varchar(15) not null,
        category varchar(20) not null check (category in ('KIRANA','SUPERMARKET','FRUITS_VEGETABLES','DAIRY','BAKERY','ORGANIC')),
        name varchar(80) not null,
        logo_url varchar(100),
        slug varchar(100) not null unique,
        address_line varchar(250) not null,
        status_reason varchar(300),
        service_pincodes varchar(400) not null,
        primary key (id)
    );

    create table stored_images (
        size_bytes integer not null,
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        shop_id bigint not null,
        content_type varchar(20) not null,
        data bytea not null,
        primary key (id)
    );

    create table users (
        monthly_budget numeric(10,2),
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        role varchar(10) not null,
        account_status varchar(12),
        phone varchar(15),
        name varchar(100) not null,
        email varchar(150) not null unique,
        email_key varchar(150) unique,
        password_hash varchar(200) not null,
        primary key (id)
    );

